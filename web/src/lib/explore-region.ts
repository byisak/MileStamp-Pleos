export type RegionCode = (typeof REGIONS)[number]["code"];
const CODES = new Set<string>(REGIONS.map((r) => r.code));

/** 코드 다듬기: '27' 그대로 · 옛 코드 강원 42 → 51, 전북 45 → 52 · '27110'처럼 길면 앞 두 자리. 모르면 null. */
export function normRegionCode(v: unknown): RegionCode | null {
  const s = String(v ?? "").trim();
  if (!/^\d{2,}$/.test(s)) return null;
  let c = s.slice(0, 2);
  if (c === "42") c = "51";
  if (c === "45") c = "52";
  return CODES.has(c) ? (c as RegionCode) : null;
}

export const regionName = (code: string) => REGIONS.find((r) => r.code === code)?.name ?? null;

/** 글 앞머리 → 코드. 긴 이름(경상북도·강원특별자치도…)과 줄인 이름(경북·강원) 둘 다. */
