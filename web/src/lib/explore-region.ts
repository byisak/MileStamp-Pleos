export function regionFromLatLng(lat: number, lng: number): RegionCode {
  let best: RegionCode = "11";
  let bestD = Infinity;
  const k = Math.cos((lat * Math.PI) / 180);
  for (const [a, b, c] of POINTS) {
    const d = (a - lat) ** 2 + ((b - lng) * k) ** 2;
    if (d < bestD) { bestD = d; best = c; }
  }
  return best;
}

/** 한 줄의 시·도: 이미 붙은 코드 → 주소·지역 글 → 좌표. */
export function regionOf(x: { region?: string | null; addr?: string | null; lat: number; lng: number }): RegionCode {
  return normRegionCode(x.region) ?? regionFromText(x.addr) ?? regionFromLatLng(x.lat, x.lng);
}
