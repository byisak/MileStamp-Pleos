/** '경북 경주시 …' · '경상북도 …' · '대구광역시 …' · '서울' → 코드. 앞머리가 시·도가 아니면 null. */
export function regionFromText(s: string | null | undefined): RegionCode | null {
  const head = String(s ?? "").trim().split(/\s+/)[0] ?? "";
  if (!head) return null;
  for (const [p, c] of PREFIX) if (head.startsWith(p)) return c;
  return null;
}

